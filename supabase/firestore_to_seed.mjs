// Firestore snapshot docs (public read) -> supabase/seed.sql. Run: node supabase/firestore_to_seed.mjs
import { writeFileSync } from "node:fs";

const DOC = (name) => `https://firestore.googleapis.com/v1/projects/jawv-challenge-list/databases/(default)/documents/jawvclSnapshots/${name}`;
const q = (value) => value === null ? "NULL" : `'${String(value).replaceAll("'", "''")}'`;

// Firestore REST wraps every value in a one-key type object.
const plain = (value) => {
  const [kind, inner] = Object.entries(value)[0];
  if (kind === "mapValue") return Object.fromEntries(Object.entries(inner.fields ?? {}).map(([k, v]) => [k, plain(v)]));
  if (kind === "arrayValue") return (inner.values ?? []).map(plain);
  if (kind === "integerValue") return Number(inner);
  if (kind === "doubleValue") return Number(inner);
  return inner;
};

const rows = (type, doc) => {
  const maps = doc.challenges.map((challenge, index) =>
    `(${[challenge.levelId, type, challenge.name, challenge.creator, challenge.verifier, challenge.description, challenge.video, challenge.length, challenge.objectCount].map(q).join(", ")}, ${challenge.tempRank}, ${index + 1})`);
  const known = new Set(doc.challenges.map((challenge) => challenge.levelId));
  const records = Object.entries(doc.clearersByLevelId)
    .filter(([levelId]) => known.has(levelId))
    .flatMap(([levelId, clearers]) => clearers.map((clearer) =>
      `(${q(levelId)}, ${q(clearer.player)}, ${clearer.percent ?? "NULL"}, ${clearer.time ?? "NULL"}, ${q(clearer.platform)})`));
  return { maps, records };
};

const selfCheck = () => {
  const doc = { challenges: [{ tempRank: true, name: "O'Hara", creator: "c", verifier: "v", description: "", video: "", levelId: "1", length: "", objectCount: "0" }], clearersByLevelId: { 1: [{ player: "p", time: 1.5, platform: "PC" }], 9: [{ player: "ghost", percent: 100, platform: "PC" }] } };
  const { maps, records } = rows("platformer", doc);
  if (!maps[0].includes("'O''Hara'") || !maps[0].endsWith("true, 1)")) throw new Error("map row wrong: " + maps[0]);
  if (records.length !== 1 || !records[0].includes("NULL, 1.5")) throw new Error("record rows wrong: " + records.join("|"));
  if (plain({ mapValue: { fields: { n: { integerValue: "7" } } } }).n !== 7) throw new Error("decode wrong");
};

selfCheck();

const docs = await Promise.all(["classic", "platformer"].map(async (name) => [name, plain({ mapValue: { fields: (await (await fetch(DOC(name))).json()).fields } })]));
const all = docs.map(([name, doc]) => rows(name, doc));
const sql = [
  "-- Generated by supabase/firestore_to_seed.mjs. Run after schema.sql.",
  "begin;",
  "insert into maps (level_id, type, name, creator, verifier, description, video, length, object_count, temp_rank, position) values",
  all.flatMap((part) => part.maps).join(",\n") + ";",
  "",
  "insert into records (level_id, player, percent, time, platform) values",
  all.flatMap((part) => part.records).join(",\n") + ";",
  "commit;",
  "",
].join("\n");

writeFileSync(new URL("./seed.sql", import.meta.url), sql);
console.log(`maps ${all.reduce((n, p) => n + p.maps.length, 0)}, records ${all.reduce((n, p) => n + p.records.length, 0)} -> supabase/seed.sql`);
