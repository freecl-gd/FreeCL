-- Read-only (a session-local temp table only). Prints the live public schema as one SQL
-- script in the `schema_sql` cell; save it as supabase/schema.sql. The output runs as is on
-- an empty Supabase project.
-- The query runs inside DO because the Supabase SQL Editor rejects it as a top-level SELECT
-- ("relation \"public\" does not exist") although Postgres runs it fine.
-- Database Webhook triggers are left out on purpose: their arguments hold NOTIFY_SECRET.
-- They live in notify-map-webhook.sql with a placeholder.
create temp table if not exists schema_export (schema_sql text);
truncate schema_export;
do $x$
begin
  execute $q$insert into schema_export
with
types as (
  select string_agg(format('create type public.%I as enum (%s);', t.typname,
           (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid)),
         E'\n' order by t.typname) as s
    from pg_type t join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public' and t.typtype = 'e'
),
seed as (
  select string_agg(format('insert into public.admin_roles (id, name) values (%s, %L) on conflict (id) do nothing;', id, name), E'\n' order by id) as s
    from public.admin_roles
),
tbl as (
  select c.oid, c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind in ('r', 'p')
),
tables as (
  select string_agg(format(E'create table public.%I (\n%s\n);', t.relname,
    (select string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
              case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end,
              case when a.attnotnull then ' not null' else '' end,
              coalesce(' default ' || pg_get_expr(d.adbin, d.adrelid), '')), E',\n' order by a.attnum)
       from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
      where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped)), E'\n\n' order by t.relname) as s
  from tbl t
),
cons as (
  select string_agg(format('alter table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid)),
                    E'\n' order by co.contype = 'f', t.relname, co.conname) as s
    from pg_constraint co join tbl t on t.oid = co.conrelid
),
funcs as (
  select string_agg(pg_get_functiondef(p.oid) || ';', E'\n\n' order by p.proname, p.oid) as s
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prokind in ('f', 'p')
     and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
views as (
  select string_agg(format(E'create view public.%I as\n%s', c.relname, pg_get_viewdef(c.oid, true)), E'\n\n' order by c.relname) as s
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'v'
),
idx as (
  select string_agg(pg_get_indexdef(i.indexrelid) || ';', E'\n' order by 1) as s
    from pg_index i join tbl t on t.oid = i.indrelid
   where not exists (select 1 from pg_constraint c where c.conindid = i.indexrelid)
),
trg as (
  select string_agg(pg_get_triggerdef(tg.oid) || ';', E'\n' order by c.relname, tg.tgname) as s
    from pg_trigger tg join pg_class c on c.oid = tg.tgrelid join pg_namespace n on n.oid = c.relnamespace
   where not tg.tgisinternal
     and (n.nspname = 'public' or (n.nspname = 'auth' and c.relname = 'users'))
     and tg.tgfoid <> 'supabase_functions.http_request'::regproc
),
rls as (
  select string_agg(format('alter table public.%I enable row level security;', t.relname), E'\n' order by t.relname) as s
    from tbl t join pg_class c on c.oid = t.oid where c.relrowsecurity
),
pol as (
  select string_agg(format(E'create policy %I on %I.%I as %s for %s to %s%s%s;', policyname, schemaname, tablename,
                           permissive, cmd, array_to_string(roles, ', '),
                           coalesce(E'\n  using (' || qual || ')', ''), coalesce(E'\n  with check (' || with_check || ')', '')),
                    E'\n\n' order by schemaname, tablename, policyname) as s
    from pg_policies where schemaname in ('public', 'storage')
),
tgrants as (
  select string_agg(format('grant %s on public.%I to %I;', privs, table_name, grantee), E'\n' order by table_name, grantee) as s
    from (select table_name, grantee, string_agg(privilege_type, ', ' order by privilege_type) as privs
            from information_schema.role_table_grants
           where table_schema = 'public' and grantee in ('anon', 'authenticated', 'service_role')
           group by 1, 2) g
),
fgrants as (
  select string_agg(stmt, E'\n' order by stmt) as s from (
    select format('revoke all on function %s from public;', p.oid::regprocedure) as stmt
      from pg_proc p join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public' and p.proacl is not null
       and not exists (select 1 from aclexplode(p.proacl) a where a.grantee = 0)
    union all
    select format('grant execute on function %s to %I;', p.oid::regprocedure, r.rolname)
      from pg_proc p join pg_namespace n on n.oid = p.pronamespace
     cross join lateral aclexplode(p.proacl) a join pg_roles r on r.oid = a.grantee
     where n.nspname = 'public' and r.rolname in ('anon', 'authenticated', 'service_role')) x
),
buckets as (
  select string_agg(format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %s, %s, %L) on conflict (id) do nothing;',
                           b.id, b.name, case when b."public" then 'true' else 'false' end, coalesce(b.file_size_limit::text, 'null'), b.allowed_mime_types), E'\n') as s
    from storage.buckets b
)
select concat_ws(E'\n\n',
  '-- FreeCL schema, exported from the live database by supabase/export-schema.sql.',
  'set check_function_bodies = off;',
  '-- Types', (select s from types),
  '-- Tables', (select s from tables),
  '-- Functions', (select s from funcs),
  '-- Constraints', (select s from cons),
  '-- Views', (select s from views),
  '-- Indexes', (select s from idx),
  '-- Triggers (Database Webhooks: notify-map-webhook.sql)', (select s from trg),
  '-- Row level security', (select s from rls),
  '-- Policies', (select s from pol),
  '-- Table grants (Supabase grants everything by default; start from nothing)',
  'revoke all on all tables in schema public from anon, authenticated, service_role;', (select s from tgrants),
  '-- Function grants (functions not listed keep the default PUBLIC execute)',
  'revoke execute on all functions in schema public from anon, authenticated, service_role;', (select s from fgrants),
  '-- Storage', (select s from buckets),
  '-- Seed rows', (select s from seed)) as schema_sql$q$;
end
$x$;
select schema_sql from schema_export;
